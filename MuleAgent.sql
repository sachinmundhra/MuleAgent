CREATE OR REPLACE VIEW F_TXN_VELOCITY AS
SELECT
  ACCOUNT_ID,
  COUNT(*) OVER (PARTITION BY ACCOUNT_ID, DATE(TXN_TS)) AS TXN_COUNT_DAY,
  SUM(AMOUNT) OVER (PARTITION BY ACCOUNT_ID, DATE(TXN_TS)) AS AMT_DAY
FROM TRANSACTIONS;

CREATE OR REPLACE VIEW F_NETWORK AS
SELECT
  ACCOUNT_ID,
  COUNT(DISTINCT COUNTERPARTY_ID) AS UNIQUE_COUNTERPARTIES
FROM TRANSACTIONS
GROUP BY ACCOUNT_ID;

CREATE OR REPLACE VIEW F_FLOW AS
SELECT
  ACCOUNT_ID,
  SUM(CASE WHEN TXN_TYPE='CREDIT' THEN AMOUNT END) AS IN_AMT,
  SUM(CASE WHEN TXN_TYPE='DEBIT' THEN AMOUNT END) AS OUT_AMT,
  OUT_AMT / NULLIF(IN_AMT,0) AS FLOW_RATIO
FROM TRANSACTIONS
GROUP BY ACCOUNT_ID;


CREATE OR REPLACE TABLE FEATURE_STORE AS
SELECT
    t.ACCOUNT_ID,

    /* Transaction volume & velocity */
    COUNT(*) AS TOTAL_TXNS,
    COUNT(DISTINCT DATE(t.TXN_TS)) AS ACTIVE_DAYS,
    SUM(t.AMOUNT) AS TOTAL_AMOUNT,

    /* Credit vs Debit behavior */
    SUM(CASE WHEN t.TXN_TYPE = 'CREDIT' THEN t.AMOUNT ELSE 0 END) AS TOTAL_CREDIT,
    SUM(CASE WHEN t.TXN_TYPE = 'DEBIT'  THEN t.AMOUNT ELSE 0 END) AS TOTAL_DEBIT,

    /* Flow-through ratio (classic mule signal) */
    CASE 
        WHEN SUM(CASE WHEN t.TXN_TYPE='CREDIT' THEN t.AMOUNT END) = 0 
        THEN 0
        ELSE
        SUM(CASE WHEN t.TXN_TYPE='DEBIT' THEN t.AMOUNT END) /
        SUM(CASE WHEN t.TXN_TYPE='CREDIT' THEN t.AMOUNT END)
    END AS FLOW_RATIO,

    /* Network behavior */
    COUNT(DISTINCT t.COUNTERPARTY_ID) AS UNIQUE_COUNTERPARTIES,

    /* Device / IP reuse */
    COUNT(DISTINCT t.DEVICE_ID) AS DEVICE_COUNT,
    COUNT(DISTINCT t.IP_ADDRESS) AS IP_COUNT,

    /* Account attributes */
    DATEDIFF(day, a.OPEN_DATE, CURRENT_DATE()) AS ACCOUNT_AGE_DAYS,
    CASE WHEN a.KYC_LEVEL = 'MIN_KYC' THEN 1 ELSE 0 END AS LOW_KYC_FLAG

FROM TRANSACTIONS t
JOIN ACCOUNTS a
  ON t.ACCOUNT_ID = a.ACCOUNT_ID
GROUP BY
    t.ACCOUNT_ID,
    a.OPEN_DATE,
    a.KYC_LEVEL;

select * from FEATURE_STORE;

